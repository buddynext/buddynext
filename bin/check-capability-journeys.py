#!/usr/bin/env python3
"""Report which shipped capabilities have no journey behind them.

WHY THIS EXISTS
The journey catalogue is hand-written, so "does every functionality have a
journey?" has never been answerable - you can only see the journeys someone
remembered to write, never the capability nobody thought about. Meanwhile
CAPABILITIES.md already lists what we tell buyers the product does, in their
language. That list is the right census for expectation-driven testing: a
capability is a promise, and an untested promise is the thing customers find.

HOW COVERAGE IS DETERMINED
Exactly, when a journey declares it:

    - **Covers:** cap-run-an-activity-feed-members-post-to

and heuristically otherwise, by matching significant words from the capability
question against the journey id and title. The heuristic exists ONLY to
bootstrap - it over-reports coverage, because a shared word is not a promise
kept. Every `~ likely` line is a claim to confirm and then pin with a Covers:
field. Treat `~ likely` as unknown, never as covered.

Reports both directions, because each is a different kind of lie:
  * a capability with no journey  - we ship a promise nothing checks
  * a journey matching nothing    - we test something we do not claim to sell,
                                    or the capability was renamed underneath it

Exit status is 0 always: this is a REPORT, not yet a gate. It becomes a gate
for NEW capabilities once the backlog is pinned, so turning it on does not
produce a wall of red nobody can act on.
"""
import re
import sys
from pathlib import Path

STOP = {
    'can', 'it', 'a', 'an', 'the', 'and', 'or', 'to', 'for', 'with', 'of', 'in',
    'on', 'by', 'from', 'their', 'them', 'they', 'you', 'your', 'own', 'per',
    'that', 'this', 'as', 'at', 'be', 'is', 'are', 'do', 'does', 'let', 'run',
    'set', 'up', 'out', 'so', 'into', 'each', 'any', 'all', 'when', 'who',
    'what', 'without', 'via', 'use', 'used', 'using', 'make', 'get', 'have',
}


def slug(text):
    return re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')


def words(text):
    return {w for w in re.findall(r'[a-z]{3,}', text.lower()) if w not in STOP}


def read_capabilities(path):
    """Rows of CAPABILITIES.md -> [(question, status)]."""
    caps = []
    if not path.exists():
        return caps
    for line in path.read_text(encoding='utf-8').splitlines():
        if not line.startswith('|'):
            continue
        cells = [c.strip() for c in line.strip('|').split('|')]
        if len(cells) < 2:
            continue
        question, status = cells[0], cells[1]
        how = cells[2] if len(cells) > 2 else ''
        if not question or question.lower().startswith('can it...'):
            continue
        if set(question) <= set('-: '):          # separator row
            continue
        if not re.match(r'^(YES|PARTIAL|PLANNED|NO)', status, re.I):
            continue
        caps.append((question, status, how))
    return caps


def read_journeys(path):
    """JOURNEYS.md -> [(journey_id, status, declared_covers)]."""
    journeys = []
    if not path.exists():
        return journeys
    current, status, covers = None, '', []
    for line in path.read_text(encoding='utf-8').splitlines():
        m = re.match(r'^#{2,4}\s+(J-[A-Za-z0-9-]+)', line)
        if m:
            if current:
                journeys.append((current, status, covers))
            current, status, covers = m.group(1), '', []
            continue
        if current:
            ms = re.match(r'^\s*-\s*\*\*Status:\*\*\s*([a-z]+)', line)
            if ms:
                status = ms.group(1)
            mc = re.match(r'^\s*-\s*\*\*Covers:\*\*\s*(.+)$', line)
            if mc:
                covers = [c.strip() for c in mc.group(1).split(',') if c.strip()]
    if current:
        journeys.append((current, status, covers))
    return journeys


QA_HEADER = """# QA assignment pack - browser walks

GENERATED by `bin/check-capability-journeys.py --qa-pack`. Do not hand-edit;
re-run it. It regenerates from CAPABILITIES.md, so a capability added next month
appears here without anyone maintaining a list.

## What is in here, and what is deliberately not

Only capabilities with **no automated journey behind them**. Anything the
Playwright suite already runs is excluded on purpose - re-walking it by hand
costs your time and finds nothing the suite would not have caught first.

So everything below is a promise we make to buyers that **nothing currently
checks**. That is why it is worth a human.

## How to test one

1. Read the promise. It is written in the buyer's words, not ours.
2. Log in as the role named. Append `?autologin=<username>` to any URL on the
   dev site - never type credentials.
3. Walk it as that person would, not as someone who knows where the buttons are.
4. Check the **effect**, not the presence. A control that appears is not a
   feature that works: press it and confirm the world changed - the row saved,
   the email arrived, the other member sees it.
5. Repeat at 390px, 768px and 1280px. Most of what we ship is used on a phone.

## When something is wrong

File it with the template at the bottom. Two things make a report actionable
and their absence is what sends cards back:

- **What you expected versus what happened**, in that order. "Follow button
  does nothing" is a symptom; "I pressed Follow, expected them to appear in my
  Following list, and the list is still empty after a reload" is a bug.
- **The exact URL, role and viewport.** Most of what escapes us is
  configuration-specific - it works for an admin at 1280px and fails for a
  logged-out visitor at 390px.

You do not need to know whether it is "really" a bug. If it surprised you,
report it. A wrong expectation is itself worth knowing: it means the product
taught you the wrong thing.

---

"""

QA_FOOTER = """
---

## Bug report template

```
Title:    [QA] <what a person would say went wrong>

Promise:  <the capability line from this pack>
Role:     <anon | member | moderator | admin>  Viewport: <390 | 768 | 1280>
URL:      <exact URL where it happened>

Expected: <what you thought would happen, and why>
Actual:   <what happened instead>
Steps:    1. ...
          2. ...

Evidence: <screenshot, and the error from the browser console if any>
Config:   <theme, and anything non-default you switched on>
```

Open the browser console (F12) before you start. A red error there usually turns
a vague "it did nothing" into a one-line fix - the comment editor was broken for
two days and the console said exactly why the whole time.
"""


# Where to start, inferred from the promise and from the services/routes named
# in the CAPABILITIES "How" column. A tester should never have to guess the
# entry point - that guesswork is what turns a 20-minute walk into an afternoon,
# and it is why generic "test the feed" assignments come back vague.
ROUTE_HINTS = [
    (r'admin|settings|menu|email|slug|white ?label|licen|webhook|banned|rate.?limit',
     'admin', '/wp-admin/admin.php?page=buddynext'),
    (r'register|log ?in|sign in|two.?factor|2fa|password|invite|onboard',
     'anon (use a private window)', '/auth/'),
    (r'space', 'member', '/spaces/'),
    (r'report|suspend|shadow|appeal|moderat', 'moderator', '/moderation/'),
    (r'message|dm\b|inbox', 'member', '/messages/'),
    (r'notification|alert', 'member', '/notifications/'),
    (r'profile|follow|connect|block|member type|online|last active',
     'member', '/members/'),
    (r'feed|post|comment|react|bookmark|reshare|poll|hashtag|announce',
     'member', '/activity/'),
    (r'search|discover|explore', 'member', '/search/'),
    (r'pwa|install|mobile app|api|rest', 'member', '/'),
]



# What most people touch, every session. Ordering the walk sheet by "what has no
# journey" put social login, PWA install and outbound webhooks at the top while
# posting, load-more, buttons and spaces sat below them - and those basics are
# where every bug this session actually came from (comment edit, hashtag
# controls, feed pagination). Rarity is not the same as unimportance, but a
# tester's first hour belongs to the paths 70-80% of members use daily.
#
# ESSENTIAL is matched against the capability question, so it re-tiers itself as
# CAPABILITIES.md changes rather than being a list someone maintains.
ESSENTIAL = re.compile(
    r'feed|post|comment|repl|react|bookmark|reshare|share|poll|'
    r'space|join|member|profile|follow|connect|notification|'
    r'search|discover|explore|upload|image|video|photo|album|'
    r'edit|delete|draft|mention|hashtag|online|directory|'
    # The front door: every member registers and logs in. Social sign-in and
    # two-factor stay EDGE - they are optional paths, and `log ?in` deliberately
    # does not match "Sign in with Google".
    r'register|log ?in|sign ?up|onboard',
    re.I,
)


def tier_of(question, how):
    # Matched against the QUESTION ONLY, never the "How" column. Including the
    # implementation pulled social sign-in and two-factor into ESSENTIAL because
    # the classes behind them are named `...Login`, and `log ?in` matches
    # "login". The tier has to follow the promise a buyer reads, not the code
    # that happens to serve it.
    del how  # deliberately unused; see above
    return 'ESSENTIAL' if ESSENTIAL.search(question) else 'EDGE'


def infer_context(question, how):
    haystack = f'{question} {how}'.lower()
    for pattern, role, url in ROUTE_HINTS:
        if re.search(pattern, haystack):
            return role, url
    return 'member', '/'


def expectation(question):
    """Turn the buyer's question into the sentence a tester should verify."""
    q = question.strip().rstrip('?')
    q = re.sub(r'^(Can it|Does it|Is it possible to)\s+', '', q, flags=re.I)
    q = re.sub(r'^(Let|Allow)\s+', '', q, flags=re.I)
    return q[0].upper() + q[1:] if q else question


def emit_qa_pack(rows):
    """rows: [(label, question, status, how)] -> markdown assignment pack."""
    out = [QA_HEADER]
    ess = [r for r in rows if tier_of(r[1], r[3]) == 'ESSENTIAL']
    edge = [r for r in rows if tier_of(r[1], r[3]) == 'EDGE']
    out.append(f'**{len(rows)} promises need a browser walk: '
               f'{len(ess)} essential, {len(edge)} edge.**\n')
    out.append('Walk the ESSENTIAL block first and finish it before starting the')
    out.append('other. It is the ground almost every member covers in every')
    out.append('session, and it is where every bug we shipped this month came')
    out.append('from. An edge case found while the basics are still unwalked is')
    out.append('a bug we would have traded for a broken button.\n')

    for tier_name, group, blurb in (
        ('ESSENTIAL', ess, 'Daily-use paths. Do these first, in order.'),
        ('EDGE', edge, 'Real promises, rarer use. Only after ESSENTIAL is done.'),
    ):
        if not group:
            continue
        out.append(f'\n# {tier_name} - {len(group)} to walk\n')
        out.append(f'_{blurb}_\n')
        for i, (label, q, st, how) in enumerate(group, 1):
            role, url = infer_context(q, how)
            flag = '' if st.upper().startswith('YES') else f'  **[{st}]**'
            out.append(f'### {tier_name[:3]}-{i}. {q}{flag}  _({label})_')
            out.append('')
            out.append(f'- **Verify:** {expectation(q)} - and that it actually took effect,')
            out.append('  not merely that the control is on screen.')
            out.append(f'- **As:** {role}   **Start at:** `{url}`')
            if how:
                out.append(f'- **Lives in:** {how}')
            out.append('- **Result:** pass / fail / surprised -> '
                       '390 [ ]   768 [ ]   1280 [ ]')
            out.append('')
    out.append(QA_FOOTER)
    return '\n'.join(out)


def main():
    root = Path(__file__).resolve().parent.parent
    pro = root.parent / 'buddynext-pro'
    qa_pack = '--qa-pack' in sys.argv

    catalogue = pro / 'free-internal' / 'docs' / 'qa' / 'JOURNEYS.md'
    journeys = read_journeys(catalogue)
    if not journeys:
        print(f'no journeys parsed from {catalogue}', file=sys.stderr)
        return 0

    # A journey only counts as real coverage if a spec actually runs it.
    RUNNING = {'implemented'}

    sources = [('free', root / 'CAPABILITIES.md'), ('pro', pro / 'CAPABILITIES.md')]
    matched_journeys = set()
    total_gaps = 0
    qa_rows = []

    for label, cap_path in sources:
        caps = read_capabilities(cap_path)
        if not caps:
            continue
        if not qa_pack:
            print(f'\n=== {label}: {len(caps)} shipped capabilities ===')
        gaps, weak = [], []
        for question, status, how in caps:
            if status.upper().startswith(('PLANNED', 'NO')):
                continue                              # not shipped, not a promise
            cap_id = 'cap-' + slug(question)[:60]
            cw = words(question)

            exact = [j for j in journeys if cap_id in j[2]]
            likely = [
                j for j in journeys
                if not exact and len(cw & words(j[0])) >= 2
            ]
            for j in exact + likely:
                matched_journeys.add(j[0])

            if exact:
                if any(j[1] in RUNNING for j in exact):
                    continue
                weak.append((question, [j[0] for j in exact], 'declared but no spec runs it'))
            elif likely:
                weak.append((question, [j[0] for j in likely], '~ likely - CONFIRM and pin with Covers:'))
            else:
                gaps.append((question, status))
                qa_rows.append((label, question, status, how))

        if qa_pack:
            continue
        print(f'  no journey at all : {len(gaps)}')
        print(f'  needs confirming  : {len(weak)}')
        total_gaps += len(gaps)
        for q, s in gaps:
            print(f'    GAP   [{s}] {q}')
        for q, js, why in weak:
            print(f'    ?     {q}\n            {why}: {", ".join(js)}')

    if qa_pack:
        # Written into Pro's free-internal/docs/qa, alongside JOURNEYS.md and
        # COVERAGE.md. free's own docs/qa/ is gitignored, so a pack generated
        # there would never reach the person meant to walk it.
        dest = pro / 'free-internal' / 'docs' / 'qa' / 'QA-ASSIGNMENT-PACK.md'
        dest.write_text(emit_qa_pack(qa_rows), encoding='utf-8')
        print(f'wrote {len(qa_rows)} capabilities to {dest}')
        return 0

    orphans = [j for j in journeys if j[0] not in matched_journeys]
    print(f'\n=== journeys matching no capability: {len(orphans)} ===')
    for j, st, _ in orphans:
        print(f'    ORPHAN [{st or "?"}] {j}')

    print(f'\nsummary: {total_gaps} shipped capabilities with no journey, '
          f'{len(orphans)} journeys with no capability')
    print('report only - not a gate yet. Pin each "?" with a Covers: field.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
